"""Generates Rules.java (theme rules, dictionary, filler words) from the desktop launcher's C++ agent code,
so the Android app understands requests exactly like the desktop Warden.

Usage: python3 gen_rules.py <repo root> <output Rules.java>
"""
import html
import re
import sys

root, out = sys.argv[1], sys.argv[2]
plan = open(f"{root}/launcher/modplatform/agent/ModpackPlan.cpp", encoding="utf-8").read()
translator = open(f"{root}/launcher/modplatform/agent/SearchTranslator.cpp", encoding="utf-8").read()
ts = open(f"{root}/launcher/resources/translations/sculk_ru.ts", encoding="utf-8").read()

# Russian titles of the themes from the launcher translation
russian = {}
for block in re.findall(r"<message[^>]*>.*?</message>", ts, re.S):
    src = re.search(r"<source>(.*?)</source>", block, re.S)
    tr = re.search(r"<translation[^>]*>(.*?)</translation>", block, re.S)
    if src and tr and tr.group(1).strip():
        russian.setdefault(html.unescape(src.group(1)), html.unescape(tr.group(1)))


def jstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def jlist(items):
    return "new String[] { " + ", ".join(jstr(i) for i in items) + " }"


rules_src = plan[plan.index("s_rules = {"):plan.index("return s_rules;")]
rules = re.findall(r'\{\s*QT_TRANSLATE_NOOP\("ModpackAgent", "([^"]+)"\),\s*\{([^}]*)\},\s*\{([^}]*)\},\s*(\d+)\s*\}', rules_src, re.S)
assert len(rules) > 20, len(rules)

dict_src = translator[translator.index("s_dictionary[] = {"):translator.index("// Words that carry no meaning")]
entries = re.findall(r'\{\s*"([^"]+)",\s*"([^"]+)"\s*\}', dict_src)
filler_src = translator[translator.index("s_fillers = {"):translator.index("return s_fillers;")]
fillers = sorted(set(re.findall(r'"([^"]+)"', filler_src)))

lines = [
    "// Generated by android/tools/gen_rules.py from the desktop launcher's agent code. Do not edit by hand.",
    "package com.sculkshoot.client;",
    "",
    "final class Rules {",
    "    private Rules() {}",
    "",
    "    static final class ThemeRule {",
    "        final String title;",
    "        final String[] triggers;",
    "        final String[] queries;",
    "        final int count;",
    "",
    "        ThemeRule(String title, String[] triggers, String[] queries, int count) {",
    "            this.title = title;",
    "            this.triggers = triggers;",
    "            this.queries = queries;",
    "            this.count = count;",
    "        }",
    "    }",
    "",
    "    static final ThemeRule[] THEMES = {",
]
for title, triggers, queries, count in rules:
    t = re.findall(r'"([^"]+)"', triggers)
    q = re.findall(r'"([^"]+)"', queries)
    lines.append(f"        new ThemeRule({jstr(russian.get(title, title))}, {jlist(t)}, {jlist(q)}, {count}),")
lines += ["    };", "", "    /** Russian word beginnings and their English meaning; the longest matching stem wins. */",
          "    static final String[][] DICTIONARY = {"]
for stem, en in entries:
    lines.append(f"        {{ {jstr(stem)}, {jstr(en)} }},")
lines += ["    };", "", "    /** Words that carry no meaning for a search. */", "    static final String[] FILLERS = {"]
for i in range(0, len(fillers), 8):
    lines.append("        " + ", ".join(jstr(f) for f in fillers[i:i + 8]) + ",")
lines += ["    };", "}", ""]
open(out, "w", encoding="utf-8").write("\n".join(lines))
print(f"{len(rules)} themes, {len(entries)} dictionary entries, {len(fillers)} fillers")
